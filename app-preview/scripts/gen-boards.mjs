// Compile the Claude Design canvas (design/canvas/*.dc.html) into one JS module the preview can run.
// Each board keeps its own template and logic, so the preview always matches the canvas.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../../design/canvas/', import.meta.url);
const out = new URL('../src/boards.gen.js', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.dc.html')).sort();
const images = readdirSync(new URL('img/', dir)).filter((f) => /\.(jpe?g|png|webp)$/.test(f));

let js = '// Generated by scripts/gen-boards.mjs from design/canvas. Do not edit by hand.\n';
images.forEach((f, i) => { js += `import img${i} from '../../design/canvas/img/${f}';\n`; });
js += `export const images = {${images.map((f, i) => `${JSON.stringify('img/' + f)}: img${i}`).join(', ')}};\n`;
js += `export const canvas = ${readFileSync(new URL('canvas.json', dir), 'utf8').trim()};\n`;
js += 'export const boards = {\n';
for (const f of files) {
  const html = readFileSync(new URL(f, dir), 'utf8');
  const tpl = (html.match(/<x-dc>([\s\S]*?)<\/x-dc>/) || [])[1];
  if (tpl == null) throw new Error(`${f}: no <x-dc> template`);
  const sm = html.match(/<script type="text\/x-dc" data-dc-script(?: data-props='([^']*)')?>([\s\S]*?)<\/script>/);
  const props = sm && sm[1] ? sm[1] : '{}';
  const code = sm ? sm[2] : '';
  const make = /class Component/.test(code) ? `(DCLogic) => {\n${code}\nreturn Component;\n}` : 'null';
  js += `  ${JSON.stringify(f.replace('.dc.html', ''))}: { template: ${JSON.stringify(tpl)}, props: ${props}, make: ${make} },\n`;
}
js += '};\n';
writeFileSync(out, js);
console.log(`src/boards.gen.js: ${files.length} boards, ${images.length} images, ${(js.length / 1024).toFixed(0)} KB`);
